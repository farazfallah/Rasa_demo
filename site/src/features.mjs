export function featurePage(f, guides = []) {
  const path = `/features/${f.slug}`;
  const trail = [
    ['/', 'خانه'],
    ['/features', 'امکانات'],
    [path, f.name],
  ];
  const toc = f.sections.map((s, i) => `<li><a href="#s${i + 1}">${esc(s.h2)}</a></li>`).join('');
  const sections = f.sections
    .map(
      (s, i) => `<section class="f-section" id="s${i + 1}">
        <h2>${esc(s.h2)}</h2>
        <p>${esc(s.p)}</p>
        ${s.bullets ? `<ul class="checks">${s.bullets.map((b) => `<li>${esc(b)}</li>`).join('')}</ul>` : ''}
        ${s.after ? `<p>${esc(s.after)}</p>` : ''}
        ${s.figure ? `<figure class="f-figure"><img src="/assets/shots/${s.figure[0]}.jpg" alt="${esc(s.figure[1])}" width="1600" height="1000" loading="lazy"><figcaption>${esc(s.figure[1])}</figcaption></figure>` : ''}
      </section>`,
    )
    .join('\n');
  const related = f.related
    .map((slug) => bySlug.get(slug))
    .filter(Boolean)
    .map((r) => `<a class="module" href="/features/${r.slug}">${icon(r.icon)}<b>${esc(r.name)}</b><span>${esc(r.short)}</span></a>`)
    .join('');
  const body = `
  <section class="page-hero">
    <div class="hero-bg" aria-hidden="true"></div>
    <div class="container">
      ${breadcrumbs(trail)}
      <div class="page-hero-inner">
        <div>
          <p class="eyebrow">${icon(f.icon)} ${esc(f.name)}</p>
          <h1>${esc(f.h1)}</h1>
          <p class="lead">${esc(f.lead)}</p>
          <div class="hero-cta">
            <a class="btn btn-primary btn-lg" href="/demo">درخواست دمو رایگان ${icon('arrow')}</a>
            <a class="btn btn-ghost btn-lg" href="#s1">جزئیات</a>
          </div>
        </div>
        ${shotHtml(f)}
      </div>
    </div>
  </section>

  <div class="container article-layout">
    <aside class="toc" aria-label="فهرست این صفحه">
      <b>در این صفحه</b>
      <ol>${toc}<li><a href="#faq">پرسش‌های رایج</a></li></ol>
    </aside>
    <div class="prose">
      ${sections}
      <section class="f-section faq" id="faq">
        <h2>پرسش‌های رایج درباره ${esc(f.name)}</h2>
        ${f.faq.map(([q, a]) => `<details><summary>${esc(q)}</summary><p>${esc(a)}</p></details>`).join('\n')}
      </section>
    </div>
  </div>

  ${
    guides.length
      ? `<section class="section">
    <div class="container">
      <div class="head center"><h2>راهنماهای مرتبط</h2></div>
      <div class="feature-grid">${guideCards(guides)}</div>
    </div>
  </section>`
      : ''
  }
  <section class="section section-tint">
    <div class="container">
      <div class="head center"><h2>امکانات مرتبط</h2></div>
      <div class="modules related">${related}</div>
    </div>
  </section>
  ${CTA}`;
  return {
    path,
    title: f.title,
    description: f.description,
    image: `/assets/shots/${f.shot}.jpg`,
    body,
    current: '/features',
    schema: [
      breadcrumbLd(trail),
      faqLd(f.faq),
      {
        '@context': 'https://schema.org',
        '@type': 'WebPage',
        name: f.title,
        description: f.description,
        url: `${SITE}${path}`,
        inLanguage: 'fa-IR',
        isPartOf: { '@type': 'WebSite', name: 'سامانه رسا', url: `${SITE}/` },
        about: { '@type': 'SoftwareApplication', name: 'سامانه رسا', applicationCategory: 'EducationalApplication' },
      },
    ],
  };
}

