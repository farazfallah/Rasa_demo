export function guidePage(g) {
  const path = `/guides/${g.slug}`;
  const trail = [
    ['/', 'خانه'],
    ['/guides', 'راهنماها'],
    [path, g.h1],
  ];
  const body = `
  <section class="page-hero compact">
    <div class="hero-bg" aria-hidden="true"></div>
    <div class="container narrow">
      ${breadcrumbs(trail)}
      <h1>${esc(g.h1)}</h1>
      <p class="lead">${esc(g.lead)}</p>
    </div>
  </section>
  <article class="container narrow prose article">
    ${g.sections.map(([h, p]) => `<section><h2>${esc(h)}</h2><p>${esc(p)}</p></section>`).join('\n')}
    <aside class="note">
      <b>نسخه نمایشی رایگان</b>
      <p>همه این موارد را می‌توانید در نسخه نمایشی رسا با اطلاعات یک مدرسه نمونه امتحان کنید. <a href="/demo">درخواست دمو</a></p>
    </aside>
  </article>
  ${CTA}`;
  return {
    path,
    title: `${g.title} | سامانه رسا`,
    description: g.description,
    type: 'article',
    body,
    current: '/guides',
    schema: [
      breadcrumbLd(trail),
      {
        '@context': 'https://schema.org',
        '@type': 'Article',
        headline: g.h1,
        description: g.description,
        datePublished: g.date,
        dateModified: g.date,
        inLanguage: 'fa-IR',
        mainEntityOfPage: `${SITE}${path}`,
        image: `${SITE}/assets/shots/dashboard.jpg`,
        author: { '@type': 'Organization', name: 'سامانه رسا' },
        publisher: { '@type': 'Organization', name: 'سامانه رسا', logo: { '@type': 'ImageObject', url: `${SITE}/assets/logo.svg` } },
      },
    ],
  };
}

